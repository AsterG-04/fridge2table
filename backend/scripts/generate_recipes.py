def build_index(recipes):
    index = {}
    for i, recipe in enumerate(recipes):
        for ingredient in recipe["ingredients"]:
            index.setdefault(ingredient, []).append(i)
    return index


def main():
    for i, recipe in enumerate(RECIPES, start=1):
        recipe["id"] = i

    assert len(RECIPES) >= 50, f"Need at least 50 recipes, have {len(RECIPES)}"

    required_keys = {
        "id", "name", "ingredients", "steps", "prep_time", "cook_time",
        "difficulty", "nutrition", "sustainability_tip", "diet_tags", "cuisine",
    }
    for recipe in RECIPES:
        missing = required_keys - recipe.keys()
        assert not missing, f"{recipe['name']} missing keys: {missing}"

    data = {
        "recipes": RECIPES,
        "index": build_index(RECIPES),
    }

    out_dir = os.path.join(os.path.dirname(__file__), "..", "data")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "recipes_full.json")

    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)

    print(f"Wrote {len(RECIPES)} recipes to {out_path}")


if __name__ == "__main__":
    main()
